const DEFAULT_LANG = "en";

function getStoredLang() {
  try {
    return localStorage.getItem("kba_lang");
  } catch (err) {
    return null;
  }
}

function setStoredLang(lang) {
  try {
    localStorage.setItem("kba_lang", lang);
  } catch (err) {
    /* localStorage unavailable (e.g. private browsing); ignore */
  }
}
